"""
predict.py — Stateful Prediction Engine for Mobitel Alarm Fault Prediction

Supports two execution modes:
1. **Full batch**: Runs inference on a pre-built feature CSV.
2. **Incremental delta**: Loads only new alarm logs from data/daily_uploads/,
   merges with cached state (data/latest_predictions.csv), generates features
   for only the new time window, runs inference, and writes the updated cache
   back to disk.

Probability risk tiers (configurable):
  - HIGH   : P >= 0.70
  - MEDIUM : 0.40 <= P < 0.70
  - LOW    : P < 0.40
"""

import os
import sys
import glob
import pandas as pd
import numpy as np
import joblib
from datetime import datetime

BASE_DIR = os.path.abspath(os.path.join(os.path.dirname(__file__), '..'))
if BASE_DIR not in sys.path:
    sys.path.append(BASE_DIR)

from src.config import load_config, get_cache_path, get_delta_logs_dir
from src.feature_engineering import (
    load_prediction_cache,
    save_prediction_cache,
    load_delta_logs,
    merge_delta_with_cache,
    generate_sliding_window_features,
)

# ---------------------------------------------------------------------------
# RISK TIER THRESHOLDS
# ---------------------------------------------------------------------------
RISK_THRESHOLD_HIGH   = 0.70
RISK_THRESHOLD_MEDIUM = 0.40


def classify_risk(probability: float) -> str:
    """
    Classify a prediction probability into a risk tier.

    Tiers:
      HIGH   : P >= 0.70  — immediate attention required
      MEDIUM : 0.40 <= P < 0.70  — monitor closely
      LOW    : P < 0.40   — within normal operating range

    Parameters
    ----------
    probability : float

    Returns
    -------
    str : 'HIGH', 'MEDIUM', or 'LOW'
    """
    if probability >= RISK_THRESHOLD_HIGH:
        return 'HIGH'
    elif probability >= RISK_THRESHOLD_MEDIUM:
        return 'MEDIUM'
    else:
        return 'LOW'


# ---------------------------------------------------------------------------
# DYNAMIC FEATURE ALIGNMENT
# ---------------------------------------------------------------------------

def align_features_to_model(features_df: pd.DataFrame, model) -> pd.DataFrame:
    """
    Aligns the feature DataFrame columns to match the model's expected input columns.

    - Drops target / metadata columns.
    - Adds any missing model columns as zero-filled columns.
    - Reorders to match model's training feature order.

    Parameters
    ----------
    features_df : pd.DataFrame
        Feature matrix generated by generate_sliding_window_features().
    model : trained scikit-learn / XGBoost model with feature_names_in_ or booster.feature_names.

    Returns
    -------
    pd.DataFrame: Aligned feature matrix ready for model.predict_proba().
    """
    # Extract model's expected feature names
    if hasattr(model, 'feature_names_in_'):
        expected_cols = list(model.feature_names_in_)
    elif hasattr(model, 'named_steps'):
        # Pipeline: look at the last estimator
        last_step = list(model.named_steps.values())[-1]
        expected_cols = list(getattr(last_step, 'feature_names_in_', []))
    else:
        expected_cols = []

    # Drop non-feature columns
    drop_cols = [c for c in features_df.columns if c.startswith('target_') or c in [
        'site_id', 'node_identifier', 'enodeb_id', 'gnodeb_id', 'window_timestamp',
        '_source_file', 'time_decay_weight', 'alarm_impact_weight', 'final_alarm_weight'
    ]]
    X = features_df.drop(columns=[c for c in drop_cols if c in features_df.columns])

    if expected_cols:
        # Add missing columns as zeros
        for col in expected_cols:
            if col not in X.columns:
                X[col] = 0
        X = X[expected_cols]

    return X


# ---------------------------------------------------------------------------
# FULL BATCH PREDICTION
# ---------------------------------------------------------------------------

def predict_cell_unavailability(feature_input: pd.DataFrame, model_path: str) -> np.ndarray:
    """
    Loads trained model and predicts probabilities for cell unavailability outage
    in the next 2 hours. Uses dynamic feature alignment to handle evolving feature sets.

    Parameters
    ----------
    feature_input : pd.DataFrame
        Feature matrix row(s) to score.
    model_path : str
        Path to the saved .pkl model file.

    Returns
    -------
    np.ndarray : Probability scores (float) for each input row.
    """
    model = joblib.load(model_path)
    X = align_features_to_model(feature_input, model)
    probabilities = model.predict_proba(X)[:, 1]
    return probabilities


# ---------------------------------------------------------------------------
# INCREMENTAL DELTA PREDICTION PIPELINE
# ---------------------------------------------------------------------------

def run_incremental_prediction(
    model_path: str = None,
    delta_dir: str = None,
    cache_path: str = None,
    config: dict = None,
    output_path: str = None
) -> pd.DataFrame:
    """
    Full incremental prediction pipeline. Steps:

    1. Load persistent prediction cache (data/latest_predictions.csv).
    2. Load new daily delta alarm logs from data/daily_uploads/.
    3. Merge delta with cached alarm-level data (deduplicated, lookback-trimmed).
    4. Generate features only for timestamps newer than the cache's max window_timestamp.
    5. Run model inference with dynamic feature alignment.
    6. Assign risk tier (HIGH / MEDIUM / LOW) based on probability thresholds.
    7. Append new predictions to cache and write back to disk.
    8. Update sequence state for precursor chain continuity.

    Parameters
    ----------
    model_path : str, optional
        Path to the trained .pkl model. Defaults to models/calibrated_xgboost_outage.pkl.
    delta_dir : str, optional
        Directory containing today's uploaded alarm CSVs. Defaults to config DELTA_LOGS_DIR.
    cache_path : str, optional
        Path to persistent prediction cache. Defaults to config CACHE_PATH.
    config : dict, optional
        Pre-loaded config. Loaded from settings.json if None.
    output_path : str, optional
        Additional output path (besides cache) to write results. Optional.

    Returns
    -------
    pd.DataFrame : New prediction rows for this batch (not full cache — just today's additions).
    """
    if config is None:
        config = load_config()
    if model_path is None:
        model_path = os.path.join(BASE_DIR, 'models', 'calibrated_xgboost_outage.pkl')
    if cache_path is None:
        cache_path = get_cache_path()
    if delta_dir is None:
        delta_dir = get_delta_logs_dir()

    print(f"\n{'='*60}")
    print(f"[Incremental] Pipeline started: {datetime.now().strftime('%Y-%m-%d %H:%M:%S')}")
    print(f"{'='*60}")

    # Step 1: Load persistent cache
    cache_df = load_prediction_cache(cache_path)

    # Step 2: Load new delta alarm logs
    delta_df = load_delta_logs(delta_dir)

    if delta_df.empty:
        print("[Incremental] No new delta data. Skipping this cycle.")
        return pd.DataFrame()

    # Step 3: Merge delta with cached alarm rows
    merged_alarms = merge_delta_with_cache(delta_df, cache_df, lookback_hours=720)

    # Step 4: Generate features (incremental = only new time steps)
    new_features_df = generate_sliding_window_features(
        input_df=merged_alarms,
        config=config,
        incremental=True
    )

    if new_features_df.empty:
        print("[Incremental] No new feature rows generated. Cache is current.")
        return pd.DataFrame()

    # Step 5: Load model & run inference
    if not os.path.exists(model_path):
        print(f"[Incremental] Model not found at {model_path}. Skipping inference.")
        return new_features_df

    print(f"[Incremental] Loading model from {model_path}...")
    model = joblib.load(model_path)
    X = align_features_to_model(new_features_df, model)

    probabilities = model.predict_proba(X)[:, 1]
    new_features_df['outage_probability'] = np.round(probabilities, 4)

    # Step 6: Assign risk tier
    new_features_df['risk_tier'] = new_features_df['outage_probability'].apply(classify_risk)

    # Step 7: Append to cache and persist
    if not cache_df.empty and 'outage_probability' in cache_df.columns:
        # cache_df here is prediction rows (has outage_probability) — append new predictions
        updated_cache = pd.concat([cache_df, new_features_df], ignore_index=True)
    else:
        updated_cache = new_features_df

    save_prediction_cache(updated_cache, cache_path)

    # Step 8: Optional additional output path
    if output_path:
        os.makedirs(os.path.dirname(os.path.abspath(output_path)), exist_ok=True)
        new_features_df.to_csv(output_path, index=False)
        print(f"[Incremental] Also wrote {len(new_features_df)} new prediction rows to {output_path}")

    # Summary
    high = (new_features_df['risk_tier'] == 'HIGH').sum()
    med  = (new_features_df['risk_tier'] == 'MEDIUM').sum()
    low  = (new_features_df['risk_tier'] == 'LOW').sum()
    print(f"\n[Incremental] Batch complete. New predictions: {len(new_features_df)}")
    print(f"  🔴 HIGH   : {high}")
    print(f"  🟡 MEDIUM : {med}")
    print(f"  🟢 LOW    : {low}")
    print(f"{'='*60}\n")

    return new_features_df


# ---------------------------------------------------------------------------
# CLI / STANDALONE ENTRY POINT
# ---------------------------------------------------------------------------

if __name__ == '__main__':
    import argparse

    parser = argparse.ArgumentParser(description='Mobitel Fault Prediction — Incremental Pipeline')
    parser.add_argument('--mode', choices=['incremental', 'full'], default='incremental',
                        help='Execution mode: incremental (delta only) or full (batch).')
    parser.add_argument('--model', type=str, default=None, help='Path to model .pkl file.')
    parser.add_argument('--features', type=str, default=None,
                        help='[full mode] Path to pre-built feature CSV.')
    parser.add_argument('--output', type=str, default=None, help='Optional output CSV path.')
    args = parser.parse_args()

    if args.mode == 'incremental':
        results = run_incremental_prediction(
            model_path=args.model,
            output_path=args.output
        )
        if not results.empty:
            print(results[['site_id', 'node_identifier', 'window_timestamp',
                            'outage_probability', 'risk_tier']].to_string(index=False))

    elif args.mode == 'full':
        if not args.features:
            features_path = os.path.join(BASE_DIR, 'data', 'telecom_features_july_2026.csv')
        else:
            features_path = args.features

        model_path = args.model or os.path.join(BASE_DIR, 'models', 'calibrated_xgboost_outage.pkl')
        features_df = pd.read_csv(features_path)
        probs = predict_cell_unavailability(features_df, model_path)
        features_df['outage_probability'] = np.round(probs, 4)
        features_df['risk_tier'] = features_df['outage_probability'].apply(classify_risk)

        if args.output:
            features_df.to_csv(args.output, index=False)
            print(f"[Full] Saved {len(features_df)} predictions to {args.output}")
        else:
            print(features_df[['site_id', 'node_identifier', 'window_timestamp',
                                'outage_probability', 'risk_tier']].to_string(index=False))
